#!/usr/bin/env node
/**
 * Capture real BidetBud screens for the HyperFrames demo film.
 *
 * Run from the repo root (starts the same static + API server the e2e tests use):
 *   node demo/scripts/capture-screens.mjs
 *   node demo/scripts/capture-screens.mjs --only=desktop,mobile
 *
 * Writes WebP stills + boxes.js to demo/assets/screens/. Nothing here is mocked: every frame is
 * the actual map UI, driven through the same controls a visitor uses.
 */
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { start as startServer } from '../../scripts/lib/e2e-server.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../assets/screens');
const ONLY = (process.argv.find((a) => a.startsWith('--only=')) || '').slice(7);

fs.mkdirSync(OUT, { recursive: true });

const { server, url: BASE_URL } = await startServer(8791);
const BASE = BASE_URL.replace(/\/$/, '');

const want = (name) => !ONLY || ONLY.split(',').includes(name);

async function ready(page) {
  await page.waitForFunction(
    () => {
      const el = document.getElementById('countLabel');
      return el && el.textContent && !/loading/i.test(el.textContent);
    },
    { timeout: 45000 }
  );
}

/** Wait until map tiles have stopped loading and animations settled. */
async function settle(page, ms = 1400) {
  await page.waitForLoadState('networkidle').catch(() => {});
  await page.waitForTimeout(ms);
}

async function dismissPromo(page) {
  const later = page.locator('#promoOverlay.open #promoLaterBtn');
  if (await later.isVisible().catch(() => false)) await later.click();
}

/**
 * Screenshot as lossless PNG, then re-encode to WebP (about 6x smaller, visually
 * identical for UI). ffmpeg is already a HyperFrames requirement.
 */
async function shot(page, name, opts = {}) {
  const png = path.join(OUT, name + '.png');
  const webp = path.join(OUT, name + '.webp');
  await page.screenshot({ path: png, ...opts });
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', png, '-c:v', 'libwebp', '-quality', '90', '-compression_level', '6', webp]);
  fs.unlinkSync(png);
  console.log('  wrote', path.relative(process.cwd(), webp));
}

/** CSS-pixel boxes of real UI elements, so the film's callouts land exactly on them. */
const BOXES = {};
async function box(page, key, selector) {
  const b = await page.locator(selector).first().boundingBox().catch(() => null);
  if (!b) {
    console.warn('  (no box for ' + key + ': ' + selector + ')');
    return;
  }
  BOXES[key] = [Math.round(b.x), Math.round(b.y), Math.round(b.width), Math.round(b.height)];
}

function writeBoxes() {
  const file = path.join(OUT, 'boxes.js');
  let prev = {};
  if (ONLY && fs.existsSync(file)) {
    try {
      prev = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^[^=]*=\s*/, '').replace(/;\s*$/, ''));
    } catch (_) {}
  }
  const merged = { ...prev, ...BOXES };
  fs.writeFileSync(
    file,
    '/* Generated by demo/scripts/capture-screens.mjs. [x, y, w, h] in CSS px of the captured viewport. */\n' +
      'window.BB_BOXES = ' + JSON.stringify(merged, null, 1) + ';\n'
  );
  console.log('  wrote', path.relative(process.cwd(), file));
}

const browser = await chromium.launch();

async function desktop(scale = 2) {
  const ctx = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    deviceScaleFactor: scale,
    locale: 'en-US',
  });
  // Never show the "add a spot" promo over the shots.
  await ctx.addInitScript(() => {
    try {
      localStorage.setItem('bb_promo_seen', '1');
      localStorage.setItem('bidetbud_promo_seen', '1');
    } catch (_) {}
  });
  const page = await ctx.newPage();
  return { ctx, page };
}

async function open(page, query = '') {
  await page.goto(BASE + '/' + query, { waitUntil: 'domcontentloaded' });
  await ready(page);
  await settle(page, 2200);
  await dismissPromo(page);
  await settle(page, 500);
}

try {
  // 1. Desktop: US overview (the default first-visit view).
  if (want('desktop')) {
    const { ctx, page } = await desktop();
    await open(page);
    await box(page, 'us.search', '.search');
    await box(page, 'us.count', '#countLabel');
    await box(page, 'us.segmented', '#placeFilter');
    await box(page, 'us.nearMe', '#nearMeBtn');
    await box(page, 'us.add', '#addBtn');
    await box(page, 'us.map', '#map');
    await box(page, 'us.sidebar', '.sidebar');
    await shot(page, 'desktop-us');
    await ctx.close();
  }

  // 2. Desktop: whole world, hotels included, so the full dataset is on screen.
  if (want('world')) {
    const { ctx, page } = await desktop();
    await open(page, '?view=30,12,3');
    await page.locator('#limitedAccessToggle').click();
    await settle(page, 2600);
    await box(page, 'world.count', '#countLabel');
    await shot(page, 'desktop-world');
    await ctx.close();
  }

  // 3. Desktop: type "ICSD" one key at a time (acronym search), then open the result.
  //    Captured at 3x because the film pushes in tight on the search bar.
  if (want('search')) {
    const { ctx, page } = await desktop(3);
    await open(page);
    const input = page.locator('#searchInput');
    await input.click();
    await page.waitForTimeout(300);
    await shot(page, 'search-0');
    const word = 'ICSD';
    for (let i = 0; i < word.length; i++) {
      await input.pressSequentially(word[i]);
      await page.waitForTimeout(650);
      await shot(page, 'search-' + (i + 1));
    }
    // Let the map fly to the match, then blur so the dropdown closes.
    await page.locator('#locationList .card').first().waitFor({ state: 'visible', timeout: 10000 });
    await settle(page, 2600);
    await box(page, 'search.bar', '.search');
    await box(page, 'search.ac', '#searchAc');
    await box(page, 'search.card', '#locationList .card');
    await box(page, 'search.pin', '.leaflet-marker-pane > *');
    await shot(page, 'search-flown');
    await page.locator('#locationList .card').first().click();
    await page.locator('#detailOverlay.open').waitFor({ state: 'visible', timeout: 5000 });
    await settle(page, 1800);
    await box(page, 'detail.dialog', '#detailDialog');
    await shot(page, 'detail-icsd');
    await ctx.close();
  }

  // 4. Desktop: place-type filter + the country chips.
  if (want('filters')) {
    const { ctx, page } = await desktop();
    await open(page);
    await page.locator('#placeFilter [data-type="mosque"]').click();
    await settle(page, 1800);
    await box(page, 'masajid.tab', '#placeFilter [data-type="mosque"]');
    await box(page, 'masajid.count', '#countLabel');
    await shot(page, 'filter-masajid');
    await page.locator('#placeFilter [data-type="restaurant"]').click();
    await settle(page, 1800);
    await box(page, 'restaurants.tab', '#placeFilter [data-type="restaurant"]');
    await box(page, 'restaurants.count', '#countLabel');
    await shot(page, 'filter-restaurants');
    await page.locator('#placeFilter [data-type="all"]').click();
    await page.locator('details.more-filters summary').click();
    await settle(page, 900);
    await box(page, 'filters.panel', '#typeChips');
    await shot(page, 'filters-open');
    await ctx.close();
  }

  // 5. Desktop: pin-colour legend.
  if (want('legend')) {
    const { ctx, page } = await desktop();
    await open(page);
    await page.locator('#legendHelpBtn').click();
    await page.locator('#legendOverlay.open').waitFor({ state: 'visible', timeout: 5000 });
    await settle(page, 700);
    await box(page, 'legend.dialog', '#legendDialog');
    await shot(page, 'legend');
    await ctx.close();
  }

  // 6. Desktop: near me (geolocation pinned to Union Square, Manhattan).
  if (want('near')) {
    const ctx = await browser.newContext({
      viewport: { width: 1440, height: 900 },
      deviceScaleFactor: 2,
      locale: 'en-US',
      geolocation: { latitude: 40.7359, longitude: -73.9911 },
      permissions: ['geolocation'],
    });
    await ctx.addInitScript(() => {
      try { localStorage.setItem('bb_promo_seen', '1'); } catch (_) {}
    });
    const page = await ctx.newPage();
    await open(page);
    await page.locator('#nearMeBtn').click();
    await settle(page, 3200);
    await box(page, 'near.btn', '#nearMeBtn');
    await box(page, 'near.hint', '#nearMeHint');
    await box(page, 'near.radius', '#radiusRow');
    await box(page, 'near.card', '#locationList .card');
    await box(page, 'near.map', '#map');
    await box(page, 'near.you', '.user-loc-dot');
    await shot(page, 'near-me');
    await ctx.close();
  }

  // 7. Desktop: suggest-a-spot form. Filled in, NEVER submitted.
  if (want('add')) {
    const { ctx, page } = await desktop();
    await open(page);
    await page.locator('#addBtn').click();
    await page.locator('#addOverlay.open').waitFor({ state: 'visible', timeout: 5000 });
    await settle(page, 600);
    await shot(page, 'add-empty');
    // A made-up name on purpose: a real one triggers the "already on the map" hint.
    await page.locator('#addName').pressSequentially('My neighborhood cafe', { delay: 20 });
    await page.locator('#addAddress').pressSequentially('Main St, Your City', { delay: 20 });
    await page.locator('#addAddress').blur();
    await settle(page, 900);
    await box(page, 'add.dialog', '#addDialog');
    await shot(page, 'add-filled');
    await ctx.close();
  }

  // 8. Phone: map, a verified spot's bottom sheet, and the list.
  if (want('mobile')) {
    const ctx = await browser.newContext({
      viewport: { width: 390, height: 844 },
      deviceScaleFactor: 3,
      isMobile: true,
      hasTouch: true,
      locale: 'en-US',
      userAgent:
        'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1',
    });
    await ctx.addInitScript(() => {
      try { localStorage.setItem('bb_promo_seen', '1'); } catch (_) {}
    });
    const page = await ctx.newPage();
    await open(page, '?view=40.742,-73.95,11');
    await shot(page, 'mobile-map');
    await page.locator('.mobile-tab[data-view="list"]').click();
    await settle(page, 900);
    await shot(page, 'mobile-list');
    await page.locator('.mobile-tab[data-view="map"]').click();
    await page.locator('#searchInput').fill('Moka & Co');
    await settle(page, 2600);
    await shot(page, 'mobile-search');
    // Open the in-person verified Astoria listing (the one from the blog post).
    await page.locator('.search-peek-item', { hasText: 'Astoria' }).first().click();
    await page.locator('#detailOverlay.open').waitFor({ state: 'visible', timeout: 5000 });
    await settle(page, 2200);
    await shot(page, 'mobile-detail');
    await ctx.close();
  }
  writeBoxes();
} finally {
  await browser.close();
  server.close();
}
